// Regenerates src/lib/report-assets.ts (fonts and logo embedded for the PDF/PowerPoint reports,
// so they work in serverless functions without reading files). Run: node scripts/gen-report-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";

const b64 = (p) => readFileSync(new URL(`../${p}`, import.meta.url)).toString("base64");
const out = `// Generated by scripts/gen-report-assets.mjs — do not edit by hand.
// Inter font (SIL Open Font License, see assets/fonts/OFL-Inter.txt) and the Ministerio de Turismo logo.
export const INTER_400 = "${b64("assets/fonts/inter-latin-400-normal.woff")}";
export const INTER_600 = "${b64("assets/fonts/inter-latin-600-normal.woff")}";
export const INTER_700 = "${b64("assets/fonts/inter-latin-700-normal.woff")}";
export const LOGO_PNG = "${b64("public/brand/mitur-logo.png")}";
`;
writeFileSync(new URL("../src/lib/report-assets.ts", import.meta.url), out);
console.log("report assets written");
